#[cfg(test)]
mod tests {
    use super::*;
    use crate::params::ENGINE_COUNT;
    use crate::voice::Voice;

    #[test]
    fn preset_names_unique() {
        for (i, a) in PRESETS.iter().enumerate() {
            for b in &PRESETS[i + 1..] {
                assert_ne!(a.name, b.name);
            }
        }
    }

    #[test]
    fn presets_are_in_range() {
        for p in PRESETS {
            for &(param, v) in p.values {
                assert_eq!(param.sanitize(v), v, "{}: {:?}", p.name, param);
            }
        }
    }

    #[test]
    fn every_engine_has_presets() {
        for e in 0..ENGINE_COUNT {
            let n = PRESETS
                .iter()
                .filter(|p| p.patch()[Param::Engine.index()] as usize == e)
                .count();
            assert!(n >= 2, "engine {e}: {n} presets");
        }
    }

    #[test]
    fn presets_sound_and_stay_sane() {
        let fs = 96_000.0;
        for p in PRESETS {
            let mut v = Voice::new(fs, 1);
            let patch = p.patch();
            for param in crate::params::ALL_PARAMS {
                v.set_param(param, patch[param.index()]);
            }
            v.snap_params();
            v.trigger(1.0);
            let out: Vec<f32> = (0..(fs * 0.5) as usize).map(|_| v.tick()).collect();
            let peak = out.iter().fold(0.0f32, |a, &b| a.max(b.abs()));
            assert!(out.iter().all(|x| x.is_finite()), "{}", p.name);
            assert!(peak > 0.05 && peak < 2.0, "{}: peak {peak}", p.name);
        }
    }

    /// Every preset but Init is a stab like the references (see
    /// `random::tests::random_hits_are_stabs` for the measure).
    #[test]
    fn presets_are_stabs() {
        use crate::analysis::{Features, REFERENCES, nearest_reference, stab_threshold};
        let fs = 24_000.0;
        let threshold = stab_threshold(&REFERENCES);
        for p in &PRESETS[1..] {
            let mut e = crate::Engine::new(fs);
            e.load_patch(0, &p.patch());
            e.snap_params();
            e.trigger(0, 1.0);
            let (l, r) = e.render_vec((fs * 2.5) as usize);
            let d = nearest_reference(&Features::measure(&l, &r, fs), &REFERENCES);
            assert!(d <= threshold, "{}: {d:.2}", p.name);
        }
    }
}

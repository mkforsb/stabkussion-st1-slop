//! Factory voice presets.
//!
//! Most of them were found by `examples/fit.rs`, fitted to one of the
//! reference stabs each (and level-matched by `examples/stabs.rs`); the
//! hand-made ones at the end are textbook recipes: a dub minor seventh
//! through a tape echo, a Drumcode-style FM stab with its modulator two
//! octaves up, and two synced chords.

// Fitted knob positions such as 0.318 are not attempts at 1/π.
#![allow(clippy::approx_constant)]

use crate::params::{ENGINE_FM, ENGINE_SYNC, ENGINE_VA, Param, VoicePatch, default_patch};

pub struct Preset {
    pub name: &'static str,
    pub values: &'static [(Param, f32)],
}

impl Preset {
    /// Full patch: defaults overlaid with this preset's values.
    pub fn patch(&self) -> VoicePatch {
        let mut p = default_patch();
        for &(param, v) in self.values {
            p[param.index()] = param.sanitize(v);
        }
        p
    }
}

